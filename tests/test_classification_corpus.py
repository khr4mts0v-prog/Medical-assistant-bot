class PublicMedicalFormsTests(unittest.TestCase):
    def test_public_blank_forms_and_templates(self):
        self.assertGreaterEqual(len(PUBLIC_FORMS), 10)
        for filename, expected in PUBLIC_FORMS.items():
            with self.subTest(file=filename):
                path = FIXTURES / filename
                self.assertTrue(path.is_file(), f"Missing fixture: {path}")
                text = path.read_text(encoding="utf-8", errors="replace")
                self.assertGreater(len(text.strip()), 100)
                self.assertEqual(classify_document(text), expected,
                                 analyze_document(text))

    def test_synthetic_positive_and_negative_edge_cases(self):
        self.assertGreaterEqual(len(EDGE_CASES), 30)
        correct = 0
        errors = []
        for name, expected, text in EDGE_CASES:
            with self.subTest(case=name):
                actual = classify_document(text)
                if actual == expected:
                    correct += 1
                else:
                    errors.append((name, expected, actual))
                self.assertEqual(actual, expected,
                                 f"Expected {expected!r}, got {actual!r}; "
                                 f"analysis={analyze_document(text)}")
        self.assertEqual(correct, len(EDGE_CASES), errors)


if __name__ == "__main__":
    unittest.main()
