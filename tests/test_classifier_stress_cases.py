class ClassifierStressCases(unittest.TestCase):
    def test_stress_cases(self):
        errors = []
        for name, expected, text in CASES:
            with self.subTest(case=name):
                actual = classify_document(text)
                if actual != expected:
                    errors.append((name, expected, actual, analyze_document(text)))
                self.assertEqual(actual, expected, f"{name}: expected={expected!r}; actual={actual!r}; analysis={analyze_document(text)}")
        self.assertFalse(errors, errors)

if __name__ == "__main__":
    unittest.main()
